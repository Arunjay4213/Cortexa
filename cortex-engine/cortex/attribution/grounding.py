"""Grounding Score — Memory Trustworthiness Assessment.

The unsolved problem in AI agent memory: is this memory actually true?

Every memory gets a grounding_score ∈ [0, 1] based on four signals:

1. PROVENANCE (0.30 weight)
   Can we trace this memory back to a real user statement or verified source?
   - Derived from user input → high provenance
   - Generated by agent → lower provenance
   - Unknown origin → lowest provenance

2. CORROBORATION (0.25 weight)
   Do other memories support this one without contradicting it?
   - Multiple non-contradictory similar memories → high
   - Sole claim with no support → medium
   - Contradicted by other memories → low

3. EMPIRICAL (0.25 weight)
   Has this memory been validated by actual retrieval success?
   - Frequently retrieved with high attribution → validated by use
   - Retrieved but low attribution → possibly not useful
   - Never retrieved → unvalidated

4. COUNTERFACTUAL (0.20 weight)
   Does removing this memory improve or degrade transaction quality?
   - Removing degrades quality → memory is real and valuable
   - Removing improves quality → memory might be contaminated
   - No effect → memory is neutral

Pure computation engine — no DB, no IO.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from datetime import UTC, datetime

import numpy as np

from cortex.attribution.eas import compute_eas
from cortex.attribution.contradiction import _find_candidate_pairs
from cortex.attribution.coverage import _cosine_similarity_matrix


# ── Dataclasses ──────────────────────────────────────────────────────

@dataclass
class GroundingWeights:
    """Configurable weights for the four grounding signals."""
    provenance: float = 0.30
    corroboration: float = 0.25
    empirical: float = 0.25
    counterfactual: float = 0.20

    def __post_init__(self):
        total = self.provenance + self.corroboration + self.empirical + self.counterfactual
        if abs(total - 1.0) > 1e-6:
            self.provenance /= total
            self.corroboration /= total
            self.empirical /= total
            self.counterfactual /= total


@dataclass
class ProvenanceSignal:
    """Provenance trace for a memory."""
    source_type: str  # "user_input" | "agent_generated" | "derived" | "imported" | "unknown"
    source_transaction_id: str | None = None  # transaction where memory originated
    user_statement_similarity: float = 0.0  # cosine sim to nearest user query
    confidence: float = 0.0


@dataclass
class GroundingResult:
    """Complete grounding assessment for a single memory."""
    memory_id: str
    grounding_score: float           # composite ∈ [0, 1]
    provenance_score: float          # traceability to source
    corroboration_score: float       # support from other memories
    empirical_score: float           # validation through use
    counterfactual_score: float      # impact when removed
    risk_level: str                  # "trusted" | "uncertain" | "suspect" | "contaminated"
    signals: dict                    # detailed signal breakdown


@dataclass
class MemoryForGrounding:
    """Memory record with fields needed for grounding analysis."""
    id: str
    content: str
    embedding: np.ndarray
    tokens: int
    retrieval_count: int = 0
    total_attribution: float = 0.0
    mean_attribution: float = 0.0
    created_at: datetime | None = None
    source_type: str = "unknown"     # "user_input" | "agent_generated" | "derived" | "unknown"
    source_transaction_id: str | None = None


@dataclass
class TransactionForGrounding:
    """Transaction record with fields needed for grounding analysis."""
    id: str
    query_text: str
    query_embedding: np.ndarray
    response_embedding: np.ndarray
    retrieved_memory_ids: list[str]


# ── Provenance Scoring ───────────────────────────────────────────────

def _score_provenance(
    memory: MemoryForGrounding,
    all_query_embeddings: np.ndarray | None,
) -> ProvenanceSignal:
    """Score how well we can trace this memory to a verifiable source.

    user_input   → 1.0   (direct user statement)
    derived      → 0.7   (derived from user-sourced data)
    agent_generated → 0.4 (agent created it — hallucination risk)
    imported     → 0.5   (external import — trust depends on source)
    unknown      → 0.2   (no provenance — highest risk)

    Additionally, check if memory content is semantically close to any
    actual user query (high similarity = likely grounded in real conversation).
    """
    base_scores = {
        "user_input": 1.0,
        "derived": 0.7,
        "imported": 0.5,
        "agent_generated": 0.4,
        "unknown": 0.2,
    }
    base = base_scores.get(memory.source_type, 0.2)

    # Check similarity to actual user queries
    user_sim = 0.0
    if all_query_embeddings is not None and all_query_embeddings.shape[0] > 0:
        mem_emb = memory.embedding.reshape(1, -1)
        sims = _cosine_similarity_matrix(mem_emb, all_query_embeddings)
        user_sim = float(sims.max()) if sims.size > 0 else 0.0

    # Boost provenance only if the source is already trustworthy.
    # An unknown-source memory with high query similarity is MORE suspicious,
    # not less — a hallucination naturally matches user queries.
    # The boost scales with how much we already trust the source.
    trust_for_boost = {
        "user_input": 1.0,       # similarity confirms a real user statement
        "derived": 0.6,          # supports a derived insight
        "imported": 0.4,         # external source, cautious boost
        "agent_generated": 0.15, # agent might have hallucinated from query context
        "unknown": 0.0,          # no provenance = no boost, period
    }
    trust_factor = trust_for_boost.get(memory.source_type, 0.0)
    sim_boost = user_sim * 0.3 * trust_factor

    confidence = min(1.0, base + sim_boost)

    return ProvenanceSignal(
        source_type=memory.source_type,
        source_transaction_id=memory.source_transaction_id,
        user_statement_similarity=round(user_sim, 4),
        confidence=round(confidence, 4),
    )


# ── Corroboration Scoring ────────────────────────────────────────────

def _score_corroboration(
    memory: MemoryForGrounding,
    all_memories: list[MemoryForGrounding],
    contradiction_pairs: set[tuple[str, str]] | None = None,
    sim_threshold: float = 0.6,
) -> float:
    """Score how well other memories corroborate this one.

    High score: multiple similar memories support this claim
    Low score: contradicted by other memories or isolated claim

    Returns score ∈ [0, 1].
    """
    if len(all_memories) <= 1:
        return 0.5  # can't assess with single memory

    # Find memories similar to this one
    other_embs = []
    other_ids = []
    for m in all_memories:
        if m.id != memory.id:
            other_embs.append(m.embedding)
            other_ids.append(m.id)

    if not other_embs:
        return 0.5

    other_matrix = np.array(other_embs)
    mem_emb = memory.embedding.reshape(1, -1)
    sims = _cosine_similarity_matrix(mem_emb, other_matrix)[0]

    # Count supporting memories (similar but not contradicting)
    supporting = 0
    contradicting = 0
    contradiction_set = contradiction_pairs if contradiction_pairs is not None else set()

    for i, sim in enumerate(sims):
        if sim >= sim_threshold:
            pair = (min(memory.id, other_ids[i]), max(memory.id, other_ids[i]))
            if pair in contradiction_set:
                contradicting += 1
            else:
                supporting += 1

    # Score: supporting evidence minus contradictions
    if contradicting > 0:
        # Active contradiction → low corroboration
        return max(0.0, 0.3 - contradicting * 0.15)

    if supporting == 0:
        return 0.5  # isolated claim — neutral

    # More support → higher score (diminishing returns)
    return min(1.0, 0.5 + 0.15 * math.log2(1 + supporting))


# ── Empirical Scoring ────────────────────────────────────────────────

def _score_empirical(memory: MemoryForGrounding) -> float:
    """Score how well this memory has been validated through actual use.

    A memory that gets retrieved often AND has high attribution is
    empirically validated — the system finds it useful and relevant.

    Returns score ∈ [0, 1].
    """
    if memory.retrieval_count == 0:
        return 0.2  # never retrieved — unvalidated

    # Retrieval frequency factor (log scale, saturates around 20 retrievals)
    retrieval_factor = min(1.0, math.log2(1 + memory.retrieval_count) / math.log2(21))

    # Attribution quality factor
    if memory.mean_attribution > 0.3:
        attr_factor = 1.0       # high attribution = strong signal
    elif memory.mean_attribution > 0.1:
        attr_factor = 0.7       # moderate
    elif memory.mean_attribution > 0.01:
        attr_factor = 0.4       # low but nonzero
    else:
        attr_factor = 0.1       # near-zero attribution despite being retrieved = noise

    # Combined: both retrieval and attribution must be present
    return round(0.3 * retrieval_factor + 0.7 * attr_factor, 4)


# ── Counterfactual Scoring ───────────────────────────────────────────

def _score_counterfactual(
    memory: MemoryForGrounding,
    all_memories: list[MemoryForGrounding],
    transactions: list[TransactionForGrounding],
) -> float:
    """Score based on what happens when we remove this memory.

    If removing the memory degrades attribution quality → it's valuable and real.
    If removing improves quality → it might be contaminated.
    If no effect → neutral.

    Returns score ∈ [0, 1].
    """
    if not transactions:
        return 0.5  # can't assess without transactions

    # Build memory set without this memory
    before_mems = {m.id: m for m in all_memories}
    after_mems = {m.id: m for m in all_memories if m.id != memory.id}

    if not after_mems:
        return 0.5

    # Only evaluate transactions that actually retrieved this memory
    relevant_txns = [
        t for t in transactions
        if memory.id in t.retrieved_memory_ids
    ]

    if not relevant_txns:
        return 0.5  # never retrieved — can't counterfactual test

    total_delta = 0.0
    counted = 0

    for txn in relevant_txns:
        # Before: EAS with all memories including target
        before_ids = [mid for mid in txn.retrieved_memory_ids if mid in before_mems]
        after_ids = [mid for mid in txn.retrieved_memory_ids if mid in after_mems]

        if not before_ids or not after_ids:
            continue

        before_embs = np.array([before_mems[mid].embedding for mid in before_ids])
        after_embs = np.array([after_mems[mid].embedding for mid in after_ids])

        before_result = compute_eas(before_embs, txn.query_embedding, txn.response_embedding)
        after_result = compute_eas(after_embs, txn.query_embedding, txn.response_embedding)

        # Compare max scores — does the best attribution get better or worse?
        before_max = float(before_result["scores"].max())
        after_max = float(after_result["scores"].max()) if after_result["scores"].size > 0 else 0.0

        # Positive delta = removing this memory HURT quality (good — memory is real)
        # Negative delta = removing this memory HELPED quality (bad — memory is noise)
        delta = before_max - after_max
        total_delta += delta
        counted += 1

    if counted == 0:
        return 0.5

    avg_delta = total_delta / counted

    # Map delta to score:
    # delta > 0 → removing hurts → memory is valuable → high score
    # delta < 0 → removing helps → memory is contamination → low score
    # delta ≈ 0 → neutral → medium score
    if avg_delta > 0.1:
        return min(1.0, 0.7 + avg_delta)   # clearly valuable
    elif avg_delta > 0:
        return 0.5 + avg_delta * 2          # slightly valuable
    elif avg_delta > -0.1:
        return max(0.2, 0.5 + avg_delta * 3)  # slightly harmful
    else:
        return max(0.0, 0.2 + avg_delta)    # clearly harmful


# ── Main Entry Point ─────────────────────────────────────────────────

def compute_grounding_scores(
    memories: list[MemoryForGrounding],
    transactions: list[TransactionForGrounding],
    contradiction_pairs: set[tuple[str, str]] | None = None,
    weights: GroundingWeights | None = None,
) -> list[GroundingResult]:
    """Compute grounding scores for all memories.

    Args:
        memories: All active memories to assess
        transactions: Recent transactions for empirical/counterfactual signals
        contradiction_pairs: Known contradiction pairs as set of (id1, id2) tuples
        weights: Component weights (default: provenance=0.30, corroboration=0.25,
                 empirical=0.25, counterfactual=0.20)

    Returns:
        List of GroundingResult, one per memory, sorted by grounding_score ascending
        (most suspect first).
    """
    if weights is None:
        weights = GroundingWeights()

    # Pre-compute query embeddings matrix for provenance scoring
    query_embs = None
    if transactions:
        query_embs = np.array([t.query_embedding for t in transactions])

    results: list[GroundingResult] = []

    for mem in memories:
        # 1. Provenance
        prov = _score_provenance(mem, query_embs)
        provenance_score = prov.confidence

        # 2. Corroboration
        corroboration_score = _score_corroboration(
            mem, memories, contradiction_pairs,
        )

        # 3. Empirical
        empirical_score = _score_empirical(mem)

        # 4. Counterfactual
        counterfactual_score = _score_counterfactual(mem, memories, transactions)

        # Composite score
        grounding_score = (
            weights.provenance * provenance_score
            + weights.corroboration * corroboration_score
            + weights.empirical * empirical_score
            + weights.counterfactual * counterfactual_score
        )
        grounding_score = round(max(0.0, min(1.0, grounding_score)), 4)

        # Risk level
        if grounding_score >= 0.7:
            risk = "trusted"
        elif grounding_score >= 0.5:
            risk = "uncertain"
        elif grounding_score >= 0.3:
            risk = "suspect"
        else:
            risk = "contaminated"

        results.append(GroundingResult(
            memory_id=mem.id,
            grounding_score=grounding_score,
            provenance_score=round(provenance_score, 4),
            corroboration_score=round(corroboration_score, 4),
            empirical_score=round(empirical_score, 4),
            counterfactual_score=round(counterfactual_score, 4),
            risk_level=risk,
            signals={
                "source_type": prov.source_type,
                "user_query_similarity": prov.user_statement_similarity,
                "retrieval_count": mem.retrieval_count,
                "mean_attribution": mem.mean_attribution,
            },
        ))

    # Sort by grounding score ascending (most suspect first)
    results.sort(key=lambda r: r.grounding_score)
    return results
